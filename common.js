const TOKEN_KEY = "intelia_admin_token";

const storage = {
  get(key) { try { return localStorage.getItem(key); } catch { return null; } },
  set(key, value) { try { localStorage.setItem(key, value); } catch { /* yaddaş əlçatan deyil */ } },
  remove(key) { try { localStorage.removeItem(key); } catch { /* yaddaş əlçatan deyil */ } },
};

class ApiError extends Error {
  constructor(message, status, data) {
    super(message);
    this.status = status;
    this.data = data;
  }
}

async function api(path, { method = "GET", body, form, auth = true, raw = false } = {}) {
  const headers = {};
  const token = storage.get(TOKEN_KEY);
  if (auth && token) headers.Authorization = `Bearer ${token}`;

  let payload;
  if (form) payload = form;
  else if (body !== undefined) {
    headers["Content-Type"] = "application/json";
    payload = JSON.stringify(body);
  }

  let res;
  try {
    res = await fetch(API_BASE + path, { method, headers, body: payload });
  } catch {
    throw new ApiError("Serverə qoşulmaq mümkün olmadı. İnternet bağlantısını yoxlayın və ya bir az sonra yenidən cəhd edin.", 0);
  }

  if (res.status === 401 && auth) window.dispatchEvent(new CustomEvent("intelia:unauthorized"));

  if (raw && res.ok) return res;

  let data = null;
  const type = res.headers.get("content-type") || "";
  if (type.includes("application/json")) data = await res.json().catch(() => null);

  if (!res.ok) {
    let message = data && data.detail;
    if (Array.isArray(message)) message = message[0] && message[0].msg;
    throw new ApiError(message || `Xəta baş verdi (${res.status}).`, res.status, data);
  }
  return data;
}

/* ---------- Formatlama ---------- */

function esc(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;").replaceAll("'", "&#039;");
}

function money(value) {
  const n = Number(value || 0);
  return n.toLocaleString("az-AZ", { minimumFractionDigits: n % 1 ? 2 : 0, maximumFractionDigits: 2 }).replace(/ /g, " ") + " ₼";
}

function formatPhone(phone) {
  const d = String(phone || "").replace(/\D/g, "");
  if (d.length === 12 && d.startsWith("994")) return `+994 ${d.slice(3, 5)} ${d.slice(5, 8)} ${d.slice(8, 10)} ${d.slice(10)}`;
  return phone || "";
}

function formatCard(number) {
  return String(number || "").replace(/\D/g, "").replace(/(.{4})/g, "$1 ").trim();
}

const MONTHS = ["yan", "fev", "mar", "apr", "may", "iyn", "iyl", "avq", "sen", "okt", "noy", "dek"];
const MONTHS_FULL = ["Yanvar", "Fevral", "Mart", "Aprel", "May", "İyun", "İyul", "Avqust", "Sentyabr", "Oktyabr", "Noyabr", "Dekabr"];

function parseDate(value) {
  if (!value) return null;
  const d = new Date(String(value).replace(" ", "T"));
  return isNaN(d) ? null : d;
}

function formatDate(value, withTime = false) {
  const d = parseDate(value);
  if (!d) return "—";
  const date = `${d.getDate()} ${MONTHS[d.getMonth()]} ${d.getFullYear()}`;
  if (!withTime) return date;
  return `${date}, ${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
}

function timeAgo(value) {
  const d = parseDate(value);
  if (!d) return "—";
  const s = Math.floor((Date.now() - d.getTime()) / 1000);
  if (s < 60) return "indicə";
  if (s < 3600) return `${Math.floor(s / 60)} dəq əvvəl`;
  if (s < 86400) return `${Math.floor(s / 3600)} saat əvvəl`;
  if (s < 86400 * 7) return `${Math.floor(s / 86400)} gün əvvəl`;
  return formatDate(value);
}

function timeRange(start, end) {
  if (start && end) return `${start} – ${end}`;
  return start || end || "";
}

function initials(name) {
  return String(name || "?").trim().split(/\s+/).slice(0, 2).map((p) => p[0] || "").join("").toUpperCase();
}

function debounce(fn, ms = 300) {
  let t;
  return (...args) => { clearTimeout(t); t = setTimeout(() => fn(...args), ms); };
}

